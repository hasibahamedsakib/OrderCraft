/** Where the mock server keeps its "database". localStorage in the browser, a Map in tests. */
export interface KeyValueStorage {
  getItem(key: string): string | null;
  setItem(key: string, value: string): void;
  removeItem(key: string): void;
}

export function memoryStorage(): KeyValueStorage {
  const data = new Map<string, string>();
  return {
    getItem: (key) => data.get(key) ?? null,
    setItem: (key, value) => void data.set(key, value),
    removeItem: (key) => void data.delete(key),
  };
}

/** Key the server writes to; other tabs listen for `storage` events on it. */
export const SERVER_STORAGE_KEY = 'ordercraft.server.v1';
